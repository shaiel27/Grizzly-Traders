-- 0014: historial de versiones de los artículos del CMS. Idempotente.
--
-- Cada vez que se guarda un cambio en el título o el texto de una traducción, el CMS guarda ANTES la versión anterior aquí (quién y cuándo), y conserva las
-- últimas 20 por artículo e idioma. Sirve para «Restaurar» una edición hecha por error. Lo escribe y lo lee solo el servidor (llave de servicio):
-- no hay políticas, así que ni el público ni los usuarios autenticados pueden tocarla. Se borra en cascada con el artículo.
create table if not exists public.posts_historial (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.posts (id) on delete cascade,
  locale text not null check (locale in ('es', 'en')),
  title text not null,
  content_html text not null,
  meta_title text,
  meta_description text,
  editado_por text,
  motivo text not null default 'edicion' check (motivo in ('edicion', 'restauracion')),
  created_at timestamptz not null default now()
);

create index if not exists posts_historial_post_locale_idx on public.posts_historial (post_id, locale, created_at desc);

alter table public.posts_historial enable row level security;
-- Sin políticas a propósito: solo la llave de servicio (que se salta RLS) accede.
revoke all on public.posts_historial from anon, authenticated;
