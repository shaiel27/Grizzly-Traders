-- Calcular reading_time_minutes aprox (200 palabras/min)
create or replace function public.calculate_reading_time(content text)
returns int language sql immutable as $$
  select greatest(1, round((length(regexp_replace(content, '<[^>]+>', '', 'g')) / 5) / 200.0)::int);
$$;

-- Publicar posts programados (llamar via pg_cron cada minuto)
create or replace function public.publish_scheduled_posts()
returns int language plpgsql as $$
declare
  updated_count int;
begin
  update public.posts
  set status = 'published', published_at = timezone('utc'::text, now()), updated_at = timezone('utc'::text, now())
  where status = 'scheduled' and scheduled_at <= timezone('utc'::text, now())
  returning 1 into updated_count;
  return coalesce(updated_count, 0);
end $$;

-- Búsqueda full-text (uso: select * from search_posts('bitcoin ether', 'es'))
create or replace function public.search_posts(query_text text, locale_param text default 'es', limit_count int default 20)
returns setof public.posts language plpgsql as $$
begin
  return query
  select p.* from public.posts p
  where p.status = 'published'
    and p.search_vector @@ plainto_tsvector(
      case when locale_param = 'en' then 'english' else 'spanish' end,
      query_text
    )
  order by ts_rank_cd(p.search_vector, plainto_tsvector(
      case when locale_param = 'en' then 'english' else 'spanish' end,
      query_text
    )) desc, p.published_at desc
  limit limit_count;
end $$;

