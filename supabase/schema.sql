-- Función genérica updated_at
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = timezone('utc'::text, now());
  return new;
end $$;

-- Trigger updated_at en todas las tablas
create trigger trigger_categorias_updated_at before update on public.categorias for each row execute function public.set_updated_at();
create trigger trigger_tipos_activo_updated_at before update on public.tipos_activo for each row execute function public.set_updated_at();
create trigger trigger_activos_updated_at before update on public.activos for each row execute function public.set_updated_at();
create trigger trigger_perfiles_autores_updated_at before update on public.perfiles_autores for each row execute function public.set_updated_at();
create trigger trigger_fuentes_updated_at before update on public.fuentes for each row execute function public.set_updated_at();
create trigger trigger_tags_updated_at before update on public.tags for each row execute function public.set_updated_at();
create trigger trigger_posts_updated_at before update on public.posts for each row execute function public.set_updated_at();
create trigger trigger_posts_translations_updated_at before update on public.posts_translations for each row execute function public.set_updated_at();

-- Función search_vector (full-text search español + inglés)
create or replace function public.update_posts_search_vector()
returns trigger language plpgsql as $$
begin
  new.search_vector :=
    setweight(to_tsvector('spanish', coalesce(new.title, '')), 'A') ||
    setweight(to_tsvector('spanish', coalesce(new.content_html, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(new.title, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(new.content_html, '')), 'B');
  return new;
end $$;

create trigger trigger_posts_search_vector before insert or update on public.posts
for each row execute function public.update_posts_search_vector();

