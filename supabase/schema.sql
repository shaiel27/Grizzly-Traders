-- 1. TABLAS BASE
-- ==========================================

-- Categorías del blog
create table public.categorias (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- Clasificación normalizada de tipos de activo
create table public.tipos_activo (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- Símbolos financieros vinculados al tipo
create table public.activos (
  id bigint generated by default as identity primary key,
  symbol text not null unique,
  name text not null,
  tipo_id bigint references public.tipos_activo(id) on delete restrict not null,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- Perfiles de autores (vinculado a auth.users)
create table public.perfiles_autores (
  id uuid references auth.users on delete cascade primary key,
  full_name text not null,
  avatar_url text,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- Fuentes de noticias (attribution)
create table public.fuentes (
  id bigint generated by default as identity primary key,
  name text not null,
  url text,
  logo_url text,
  reliability_score int default 50 check (reliability_score between 0 and 100),
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- Tags (más flexibles que categorías)
create table public.tags (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- Posts principales
create table public.posts (
  id uuid default gen_random_uuid() primary key,
  title text not null,
  slug text not null unique,
  content_html text not null,
  meta_title text,
  meta_description text,
  og_image_url text,
  twitter_card text default 'summary_large_image',
  sentiment text check (sentiment in ('bullish', 'bearish', 'neutral')),
  cover_image_url text,
  source_url text unique,
  source_id bigint references public.fuentes(id) on delete set null,
  status text default 'draft' check (status in ('draft', 'published', 'scheduled')),
  embedding vector(1536),
  search_vector tsvector,
  view_count bigint default 0,
  reading_time_minutes int,
  is_featured boolean default false,
  author_id uuid references public.perfiles_autores(id) on delete set null,
  category_id bigint references public.categorias(id) on delete set null,
  published_at timestamptz default timezone('utc'::text, now()),
  scheduled_at timestamptz,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- Traducciones de posts (i18n ES/EN)
create table public.posts_translations (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.posts(id) on delete cascade,
  locale text not null check (locale in ('es', 'en')),
  title text not null,
  slug text not null,
  content_html text not null,
  meta_title text,
  meta_description text,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null,
  unique (post_id, locale),
  unique (locale, slug)
);

-- Relación many-to-many posts <-> activos
create table public.post_activos (
  post_id uuid references public.posts(id) on delete cascade,
  asset_id bigint references public.activos(id) on delete cascade,
  primary key (post_id, asset_id)
);

-- Relación many-to-many posts <-> tags
create table public.post_tags (
  post_id uuid references public.posts(id) on delete cascade,
  tag_id bigint references public.tags(id) on delete cascade,
  primary key (post_id, tag_id)
);

